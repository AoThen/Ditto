#include <gtest/gtest.h>
#include "../EncryptDecrypt/rijndael.h"
#include <cstring>

// NIST SP 800-38A AES-128 ECB known-vector test
TEST(Rijndael_AES128, Encrypt)
{
	unsigned char key[16] = {
		0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
		0xaf, 0x41, 0x6d, 0xa7, 0xab, 0x6f, 0xe1, 0x63
	};
	unsigned char plaintext[16] = {
		0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d,
		0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07, 0x34
	};
	unsigned char expected[16] = {
		0x3a, 0xd7, 0x7b, 0xb7, 0x6f, 0x1c, 0x70, 0x82,
		0x69, 0x4f, 0x61, 0x36, 0x94, 0x1b, 0xe5, 0x54
	};
	unsigned char output[16];

	Rijndael rijndael;
	int ret = rijndael.init(Rijndael::ECB, Rijndael::Encrypt, key, Rijndael::Key16Bytes);
	ASSERT_EQ(RIJNDAEL_SUCCESS, ret);

	ret = rijndael.blockEncrypt(plaintext, 128, output);
	ASSERT_EQ(128, ret);
	EXPECT_EQ(0, std::memcmp(output, expected, 16));
}

